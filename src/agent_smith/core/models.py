"""Pydantic data models for Agent Smith.

Covers:
- StepMetrics: telemetry and traces for each Thought -> Code -> Observation cycle.
- SolutionOutput: final benchmark result contract and solution.json writer.
- SandboxConfig: sandbox execution limits and isolation policies.
- MBPPTaskInput & SWEBenchTaskInput: input problem loader definitions.
"""

from __future__ import annotations

import os
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

