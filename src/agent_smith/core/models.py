class MBPPTaskInput(BaseModel):
    """Input structure for an MBPP benchmark task loaded from --task-file JSON."""

    model_config = ConfigDict(extra="forbid", strict=True)

    task_id: int | str = Field(..., description="Unique MBPP task identifier (e.g. 11).")
    task_definition: str = Field(..., description="Natural language problem statement.")
    function_definition: str = Field(..., description="Expected function signature or stub.")
    test_imports: list[str] = Field(
        default_factory=list, description="Import statements required by the unit tests."
    )
    test_list: list[str] = Field(
        ..., min_length=1, description="List of assert statements verifying the solution."
    )

    @classmethod
    def from_file(cls, path: Path | str) -> MBPPTaskInput:
        """Load and validate MBPPTaskInput from a JSON file."""
        file_path = Path(path)
        if not file_path.is_file():
            raise FileNotFoundError(f"MBPP task file not found: {path}")
        with open(file_path, "r", encoding="utf-8") as f:
            return cls.model_validate_json(f.read())


class SWEBenchTaskInput(BaseModel):
    """Input structure for a SWE-bench task loaded from --task-file JSON."""

    model_config = ConfigDict(extra="forbid", strict=True)

    instance_id: str = Field(
        ..., description="SWE-bench instance identifier (e.g. 'sympy__sympy-14711')."
    )
    problem_statement: str = Field(..., description="Problem description from the repository task.")
    docker_image: str = Field(..., description="Name or tag of the Docker image for this instance.")
    eval_script: str = Field(..., description="Evaluation script / command to verify the fix.")
    hints_text: str = Field(
        default="", description="Hints or discussion text associated with the task."
    )
    repo: str = Field(..., description="Target repository name (e.g. 'sympy/sympy').")

    @classmethod
    def from_file(cls, path: Path | str) -> SWEBenchTaskInput:
        """Load and validate SWEBenchTaskInput from a JSON file."""
        file_path = Path(path)
        if not file_path.is_file():
            raise FileNotFoundError(f"SWE-bench task file not found: {path}")
        with open(file_path, "r", encoding="utf-8") as f:
            return cls.model_validate_json(f.read())


def load_task_input(
    path: Path | str,
    benchmark: Literal["mbpp", "swebench"],
) -> MBPPTaskInput | SWEBenchTaskInput:
    """Helper to load either MBPPTaskInput or SWEBenchTaskInput based on benchmark type."""
    if benchmark == "mbpp":
        return MBPPTaskInput.from_file(path)
    elif benchmark == "swebench":
        return SWEBenchTaskInput.from_file(path)
    else:
        raise ValueError(f"Unknown benchmark: '{benchmark}'. Expected 'mbpp' or 'swebench'.")
