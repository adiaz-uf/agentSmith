class StepMetrics(BaseModel):
    """Telemetry and trace record for a single LLM-generate -> sandbox-execute cycle."""

    model_config = ConfigDict(extra="forbid")

    step: int = Field(..., ge=1, description="1-indexed iteration number of the cycle.")
    input_tokens: int = Field(..., ge=0, description="Tokens sent in the prompt for this step.")
    output_tokens: int = Field(..., ge=0, description="Tokens generated by the LLM for this step.")
    request_time_ms: float = Field(..., ge=0.0, description="LLM call latency in milliseconds.")
    timestamp: str = Field(
        default_factory=current_iso_timestamp,
        description="ISO 8601 timestamp when this step completed.",
    )
    api_url: str = Field(default="", description="Endpoint URL of the LLM provider used.")
    model_name: str = Field(default="", description="Model identifier used for this step.")
    llm_output: str = Field(default="", description="Raw LLM text response before code extraction.")
    sandbox_input: str = Field(default="", description="Extracted code sent to the sandbox.")
    sandbox_output: str = Field(
        default="", description="Sandbox execution result (stdout/stderr/errors)."
    )
    retries: int = Field(
        default=0,
        ge=0,
        description="Number of retries triggered for this step (due to rate limits, timeouts, etc.).",
    )

    @field_validator("timestamp")
    @classmethod
    def _validate_timestamp(cls, v: str) -> str:
        return validate_iso_8601_timestamp(v)


