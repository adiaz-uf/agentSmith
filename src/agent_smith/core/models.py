class SolutionOutput(BaseModel):
    """Final solution output artifact (solution.json)."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(..., description="Unique identifier of the evaluated task.")
    benchmark: Literal["mbpp", "swebench"] = Field(
        ..., description="Benchmark type ('mbpp' or 'swebench')."
    )
    success: bool = Field(
        ..., description="Whether the task was solved successfully according to evaluation."
    )
    solution: str = Field(
        default="",
        description="The submitted solution (MBPP: Python function code; SWE-bench: git patch).",
    )
    iterations: int = Field(
        ..., ge=0, description="Total number of agent loop iterations executed."
    )
    total_requests: int = Field(..., ge=0, description="Total number of LLM API requests made.")
    total_input_tokens: int = Field(
        ..., ge=0, description="Total input/prompt tokens consumed across all steps."
    )
    total_output_tokens: int = Field(
        ..., ge=0, description="Total output/completion tokens consumed across all steps."
    )
    total_time_seconds: float = Field(
        ..., ge=0.0, description="Total wall-clock duration of the run in seconds."
    )
    steps: list[StepMetrics] = Field(
        default_factory=list, description="Ordered list of step telemetry records."
    )
    system_prompt: str = Field(
        default="", description="Full system prompt supplied to the agent for provenance."
    )
    error: str | None = Field(
        default=None,
        description="Error message if the agent aborted or encountered an unrecoverable failure.",
    )
    timestamp: str = Field(
        default_factory=current_iso_timestamp,
        description="ISO 8601 timestamp when this solution was finalized.",
    )

    @field_validator("task_id", mode="before")
    @classmethod
    def _normalize_task_id(cls, v: Any) -> str:
        if isinstance(v, bool):
            raise ValueError("task_id cannot be a boolean")  # noqa: TRY004
        if isinstance(v, (int, str)):
            s = str(v).strip()
            if not s:
                raise ValueError("task_id cannot be empty")
            return s
        raise ValueError(f"task_id must be a string or integer, got {type(v).__name__}")

    @field_validator("timestamp")
    @classmethod
    def _validate_timestamp(cls, v: str) -> str:
        return validate_iso_8601_timestamp(v)

    def write_to_file(self, path: Path | str, indent: int = 2) -> Path:
        """Write this SolutionOutput atomically to a JSON file."""
        return write_solution_json(self, path, indent=indent)


def write_solution_json(
    solution: SolutionOutput,
    path: Path | str,
    indent: int = 2,
) -> Path:
    """Atomically write SolutionOutput to the destination path.

    Uses a temporary file in the same directory and replaces the target file,
    ensuring solution.json is never corrupted by partial writes even on crash or abort.

    Args:
        solution: SolutionOutput instance to write.
        path: Destination file path.
        indent: Indentation level for pretty-printing JSON.

    Returns:
        Path to the written file.
    """
    target = Path(path).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)

    data = solution.model_dump_json(indent=indent)

    tmp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            dir=target.parent,
            prefix=f".{target.name}.",
            suffix=".tmp",
            delete=False,
            encoding="utf-8",
        ) as tmp_file:
            tmp_path = Path(tmp_file.name)
            tmp_file.write(data)
            tmp_file.flush()
            os.fsync(tmp_file.fileno())
        tmp_path.replace(target)
    except Exception:
        if tmp_path is not None and tmp_path.exists():
            tmp_path.unlink(missing_ok=True)
        raise

    return target


